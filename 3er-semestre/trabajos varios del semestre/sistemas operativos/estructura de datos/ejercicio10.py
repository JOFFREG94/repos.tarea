#Escribir un programa que almacene en una lista los siguientes precios
# , 50, 75, 46, 22, 80, 65, 8,
# y muestre por pantalla el menor y el mayor de los precios.
# Lista de precios
precios = [50, 75, 46, 22, 80, 65, 8]

# Encontrar el menor y el mayor precio
menor = min(precios)
mayor = max(precios)

# Mostrar resultados
print(f"El precio menor es: {menor}")
print(f"El precio mayor es: {mayor}")
